#!/usr/bin/env node
/**
 * Bundles the repository's reference source plugins into importable TS modules.
 *
 * The extension cannot read `examples/sources/*.js` from a packaged build, so each reference plugin
 * is inlined as a string module. `examples/sources/peppercarrot.js` stays the single source of truth
 * for the plugin-host tests; run `pnpm sync:builtin` after editing it.
 *
 * The generated bundles are **test fixtures only**: `src/sources/builtin/index.ts` registers no
 * built-in source, so the extension ships without any comic source and every installed plugin can
 * be removed by the user.
 *
 * Pass `--check` to verify the generated modules are up to date without writing (CI-friendly): the
 * script exits non-zero when a bundle has drifted.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const EXT_ROOT = resolve(HERE, "..");
const REPO_ROOT = resolve(EXT_ROOT, "..");
const OUT_DIR = join(EXT_ROOT, "src", "sources", "builtin");

/**
 * Reference plugins kept as test fixtures (`tests/plugin-host.test.ts` runs them verbatim). They are
 * generated but deliberately **not** registered in {@link ./src/sources/builtin/index.ts}.
 *
 * @type {{ id: string, file: string, module: string, displayName: string, description: string }[]}
 */
const BUILTINS = [
  {
    id: "peppercarrot",
    file: "examples/sources/peppercarrot.js",
    module: "peppercarrot",
    displayName: "Pepper & Carrot",
    description: "Pepper & Carrot by David Revoy (CC BY 4.0) — reference implementation",
  },
];

/** Escapes a script so it can be embedded verbatim in a template literal. */
function toTemplateLiteral(source) {
  return source.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const CHECK_ONLY = process.argv.includes("--check");

/** Fails the build when a committed bundle no longer matches its source. */
async function verifyFresh(path, expected) {
  let actual = null;
  try {
    actual = await readFile(path, "utf8");
  } catch {
    return false;
  }
  return actual === expected;
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  let drifted = false;

  const header = `// AUTO-GENERATED by scripts/sync-builtin-sources.mjs — do not edit by hand.
// Source of truth: examples/sources/*.js in the Comics8 repository.
`;
  const exports = [];

  for (const entry of BUILTINS) {
    const absolute = join(REPO_ROOT, entry.file);
    const script = await readFile(absolute, "utf8");
    const moduleName = entry.module;

    const contents = `${header}
/** ${entry.description}. */
export const ${moduleName}Script = \`${toTemplateLiteral(script)}\`;

export const ${moduleName}Source = {
  id: ${JSON.stringify(entry.id)},
  displayName: ${JSON.stringify(entry.displayName)},
  script: ${moduleName}Script,
} as const;
`;
    const target = join(OUT_DIR, `${moduleName}.ts`);
    if (CHECK_ONLY) {
      if (await verifyFresh(target, contents)) {
        console.log(`ok src/sources/builtin/${moduleName}.ts`);
      } else {
        drifted = true;
        console.error(`drift src/sources/builtin/${moduleName}.ts (run pnpm sync:builtin)`);
      }
    } else {
      await writeFile(target, contents, "utf8");
      console.log(`wrote src/sources/builtin/${moduleName}.ts (${script.length} bytes)`);
    }
    exports.push(moduleName);
  }

  // The registry entry point stays empty on purpose: reference plugins above are test fixtures, and
  // a comic source the user did not install must never show up in the source manager.
  const index = `${header}
import type { BuiltinSource } from "../types";

/**
 * Plugins shipped inside the extension.
 *
 * Deliberately empty: Comics8 ships **no** comic source out of the box. Every web-comic source is a
 * \`.js\` plugin the user installs and can remove again, so nothing appears in the source manager that
 * the user did not add.
 */
export const BUILTIN_SOURCES: readonly BuiltinSource[] = [];
`;
  const indexTarget = join(OUT_DIR, "index.ts");
  if (CHECK_ONLY) {
    if (await verifyFresh(indexTarget, index)) {
      console.log("ok src/sources/builtin/index.ts");
    } else {
      drifted = true;
      console.error("drift src/sources/builtin/index.ts (run pnpm sync:builtin)");
    }
    if (drifted) process.exitCode = 1;
  } else {
    await writeFile(indexTarget, index, "utf8");
    console.log(`wrote src/sources/builtin/index.ts [${exports.join(", ")}]`);
  }
}

await main();
